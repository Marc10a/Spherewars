// Compiles Tailwind: src/styles/tailwind.css (source) -> src/app/globals.css (generated, committed).
//
// Why: the build host (Hostinger, Node 20) could not run Turbopack's CSS loader process ("node process exited
// before we could connect to it"). Shipping compiled CSS means `next build` has no Tailwind/PostCSS step at all.
//
// Usage:  npm run css          regenerate (do this after adding/changing Tailwind classes or the source CSS)
//         npm run css -- --check   exit 1 if the committed output is stale
import fs from "node:fs";
import path from "node:path";
import { compile, optimize, Polyfills } from "@tailwindcss/node";
import { Scanner } from "@tailwindcss/oxide";

const root = path.resolve(import.meta.dirname, "..");
const input = path.join(root, "src", "styles", "tailwind.css");
const output = path.join(root, "src", "app", "globals.css");

const source = fs.readFileSync(input, "utf8");
const compiler = await compile(source, {
  from: input,
  base: path.dirname(input),
  shouldRewriteUrls: true,
  onDependency: () => {},
  polyfills: Polyfills.All,
});

// Only scan source code (not the large JSON content files, which would add accidental matches).
const scanner = new Scanner({
  sources: [
  { base: path.join(root, "src"), pattern: "**/*.tsx", negated: false },
  { base: path.join(root, "src"), pattern: "**/*.ts", negated: false },
  ...compiler.sources,
] });
const css = optimize(compiler.build(scanner.scan()), { minify: true }).code;
const banner = "/* GENERATED by scripts/build-css.mjs from src/styles/tailwind.css. Do not edit; run `npm run css`. */\n";
const result = banner + css + "\n";

if (process.argv.includes("--check")) {
  const current = fs.existsSync(output) ? fs.readFileSync(output, "utf8") : "";
  if (current !== result) { console.error("src/app/globals.css is stale: run `npm run css`"); process.exit(1); }
  console.log("css: up to date");
} else {
  fs.writeFileSync(output, result);
  console.log(`css: ${(result.length / 1024).toFixed(1)} KB written to src/app/globals.css`);
}
